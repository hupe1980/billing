#!/usr/bin/env python3
"""Compile and run every Rust example on the documentation site.

The README is included into the crate with `#![doc = include_str!]`, so rustdoc
compiles and runs each of its examples and documentation rot is impossible there.
The site cannot use that trick: rustdoc needs a hidden `# Ok::<(), _>(())` trailer
wherever a snippet uses `?`, and Zola has no way to hide such a line — it would be
printed on the page.

So the snippets stay clean and are verified here instead. Each fenced `rust` block
becomes one `#[test]` in a generated, git-ignored integration test, wrapped in an
inner function that returns `Result` so `?` works exactly as it does in a doctest.

    just site-verify

Blocks marked ```rust,ignore are extracted but not run, matching rustdoc.
"""

import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTENT = ROOT / "site" / "content"
OUT = ROOT / "tests" / "site_examples.rs"

FENCE = re.compile(r"^```rust([^\n]*)\n(.*?)^```", re.S | re.M)

header = [
    "//! GENERATED by `just site-verify` — do not edit, and do not commit.",
    "//!",
    "//! One test per fenced Rust block on the documentation site. See",
    "//! `site/verify-examples.py` for why the site cannot use the README's",
    "//! `include_str!` doctest trick.",
    "#![allow(unused_imports, unused_variables, dead_code)]",
    "",
]
body, count, skipped = [], 0, 0

for md in sorted(CONTENT.rglob("*.md")):
    stem = md.relative_to(CONTENT).with_suffix("").as_posix()
    stem = re.sub(r"[^a-z0-9]+", "_", stem.lower()).strip("_")
    for i, m in enumerate(FENCE.finditer(md.read_text(encoding="utf-8"))):
        info, code = m.group(1), m.group(2)
        if "ignore" in info or "no_run" in info:
            skipped += 1
            continue
        count += 1
        body += [
            f"/// From `site/content/{md.relative_to(CONTENT).as_posix()}`.",
            "#[test]",
            f"fn {stem}_{i}() {{",
            "    fn example() -> Result<(), Box<dyn std::error::Error>> {",
            *(f"        {line}" if line.strip() else "" for line in code.rstrip().split("\n")),
            "        Ok(())",
            "    }",
            "    example().expect(\"site example failed at runtime\");",
            "}",
            "",
        ]

OUT.write_text("\n".join(header + body), encoding="utf-8")
# Format it: the file lands in `tests/`, so an unformatted one would fail
# `cargo fmt --check` for the rest of the run even though nobody wrote it by hand.
subprocess.call(["rustfmt", "--edition", "2024", str(OUT)])
print(f"generated {count} tests from the site ({skipped} marked ignore) -> {OUT.relative_to(ROOT)}")

rc = subprocess.call(
    ["cargo", "test", "--all-features", "--test", "site_examples"], cwd=ROOT
)

# Remove it again. Leaving it in `tests/` would add a test binary that every
# `cargo test` rebuilds and every mutation-testing run rebuilds ~1000 times — for a
# target that checks documentation rather than behaviour. It is regenerated in under
# a second whenever this script runs.
if rc == 0:
    OUT.unlink(missing_ok=True)
else:
    print(f"\nleft {OUT.relative_to(ROOT)} in place so the failure can be inspected")
sys.exit(rc)
